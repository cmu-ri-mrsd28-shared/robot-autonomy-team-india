"""Bake conservative local boxes from the existing Panda collision meshes.

Development utility only: NumPy + stdlib, no MuJoCo. The generated JSON is all
the geometric planner needs; mesh files are not needed on the robot PC.
"""
import json
from pathlib import Path
import struct
from itertools import product
import xml.etree.ElementTree as ET
import numpy as np


def vertices(path):
    if path.suffix=='.obj':
        return np.array([[float(x) for x in line.split()[1:4]]
                         for line in path.read_text().splitlines() if line.startswith('v ')])
    raw=path.read_bytes(); count=struct.unpack_from('<I',raw,80)[0]
    if len(raw)!=84+count*50: raise ValueError('Expected binary STL: '+str(path))
    return np.array([struct.unpack_from('<9f',raw,84+i*50+12) for i in range(count)]).reshape(-1,3)


def boxes(source):
    root=ET.parse(source).getroot()
    meshes={m.attrib['name'] if 'name' in m.attrib else Path(m.attrib['file']).stem:
            source.parent/'meshes'/m.attrib['file'] for m in root.findall('./asset/mesh')}
    result=[]
    # Use mesh-local axis-aligned boxes. Their world orientations follow FK,
    # giving Lab2-style oriented boxes that enclose every collision-mesh vertex.
    for body in root.findall('.//worldbody//body'):
        name=body.attrib['name']
        for i,geom in enumerate(body.findall('geom')):
            cls=geom.attrib.get('class','')
            if cls=='collision':
                points=vertices(meshes[geom.attrib['mesh']])
                lower,upper=points.min(axis=0),points.max(axis=0)
                center=(lower+upper)/2; half=(upper-lower)/2
            elif cls.startswith('fingertip_pad_collision_'):
                defaults=root.find(".//default[@class='"+cls+"']/geom")
                center=np.fromstring(defaults.attrib['pos'],sep=' ')
                half=np.fromstring(defaults.attrib['size'],sep=' ')
                points=center+np.array(list(product((-1,1),repeat=3)))*half
            else: continue
            result.append({'name':name+':'+str(i),'body':name,
                           'center':center.tolist(),'half_size':(half+1e-7).tolist(),
                           'vertices':np.unique(points,axis=0).tolist()})
    return {'description':'Panda convex collision vertices and enclosing broad-phase boxes; metres. Generated by build_collision_boxes.py. Original mesh licences apply.',
            'schema':1,'boxes':result}


if __name__=='__main__':
    source=Path(__file__).resolve().parents[1]/'simulation/assets/panda.xml'
    output=Path(__file__).with_name('panda_boxes.json')
    output.write_text(json.dumps(boxes(source),indent=2)+'\n')
    print('Saved',output)
